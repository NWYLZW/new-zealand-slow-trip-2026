import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createPrivateVaultPayload } from "../src/privateVault/crypto.js";

const [inputPath] = process.argv.slice(2);
const outputPath = new URL("../src/data/privateVaultPayload.js", import.meta.url);

function readHiddenLine(label) {
  if (!process.stdin.isTTY) {
    throw new Error("Run this command in an interactive terminal, or set VAULT_RECOVERY_PASSPHRASE for this command only.");
  }
  return new Promise((resolveInput, reject) => {
    let value = "";
    const stdin = process.stdin;
    process.stdout.write(label);
    stdin.setRawMode(true);
    stdin.resume();
    const onData = (chunk) => {
      const character = chunk.toString("utf8");
      if (character === "\r" || character === "\n") {
        process.stdout.write("\n");
        cleanup();
        resolveInput(value);
        return;
      }
      if (character === "\u0003") {
        cleanup();
        reject(new Error("Private-vault creation cancelled."));
        return;
      }
      if (character === "\u007f" || character === "\b") {
        value = value.slice(0, -1);
        return;
      }
      value += character;
    };
    const cleanup = () => {
      stdin.off("data", onData);
      stdin.setRawMode(false);
      stdin.pause();
    };
    stdin.on("data", onData);
  });
}

async function recoveryPassphrase() {
  const supplied = process.env.VAULT_RECOVERY_PASSPHRASE;
  if (supplied) return supplied;
  const first = await readHiddenLine("Recovery passphrase (12+ characters): ");
  const second = await readHiddenLine("Repeat recovery passphrase: ");
  if (first !== second) throw new Error("Recovery passphrases did not match.");
  return first;
}

if (!inputPath) {
  throw new Error("Usage: npm run vault:encrypt -- /absolute/path/to/private-vault.json");
}

const resolvedInput = resolve(inputPath);
let source;
try {
  source = JSON.parse(await readFile(resolvedInput, "utf8"));
} catch {
  throw new Error("The private-vault source must be a readable JSON object.");
}

const payload = await createPrivateVaultPayload(source, await recoveryPassphrase());
const moduleSource = [
  "// Generated by scripts/create-private-vault.mjs. Contains ciphertext only.",
  `export const privateVaultPayload = ${JSON.stringify(payload, null, 2)};`,
  "",
].join("\n");

await writeFile(outputPath, moduleSource, "utf8");
console.log("Encrypted private-vault payload written. Review and commit only src/data/privateVaultPayload.js.");
