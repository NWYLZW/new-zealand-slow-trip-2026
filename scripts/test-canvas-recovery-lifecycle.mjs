import assert from 'node:assert/strict';
import { observeCanvasRecovery, registerCanvasCache, repaintCanvasTree, setCanvasRepaint } from '../src/adventure/pencil/canvasRecovery.js';

globalThis.document = new EventTarget();
globalThis.window = new EventTarget();
document.visibilityState = 'visible';
const frames = new Map();
let nextFrame = 0;
globalThis.requestAnimationFrame = callback => { frames.set(++nextFrame, callback); return nextFrame; };
globalThis.cancelAnimationFrame = id => frames.delete(id);
const flush = () => { const batch = [...frames.values()]; frames.clear(); batch.forEach(callback => callback()); };
const cache = new Map([['old', 'bitmap']]);
registerCanvasCache(cache);
let count = 0;
const stop = observeCanvasRecovery(() => { assert.equal(cache.size, 0); count++; });
document.dispatchEvent(new Event('visibilitychange'));
document.dispatchEvent(new Event('resume'));
assert.equal(frames.size, 1);
flush(); assert.equal(count, 1);
document.dispatchEvent(new Event('resume'));
document.visibilityState = 'hidden';
document.dispatchEvent(new Event('visibilitychange'));
assert.equal(frames.size, 0);
document.dispatchEvent(new Event('contextrestored'));
assert.equal(frames.size, 0);
document.visibilityState = 'visible';
document.dispatchEvent(new Event('visibilitychange'));
stop();
assert.equal(frames.size, 0);
document.dispatchEvent(new Event('visibilitychange'));
assert.equal(frames.size, 0);
const canvas = {};
setCanvasRepaint(canvas, () => count++);
repaintCanvasTree({ querySelectorAll: () => [canvas, {}] });
assert.equal(count, 2);
console.log('Canvas recovery lifecycle: deduplication, hidden suspension, cache-first invalidation and final-subscriber cleanup passed.');
